function markdownText(value) {
  const special = new Set(["\\", "`", "*", "_", "{", "}", "[", "]", "(", ")", "#", "+", "-", ".", "!", "|", ">"]);
  return [...String(value ?? "")].map((character) => special.has(character) ? "\\" + character : character).join("");
}

function inlineCode(value) {
  return "`" + String(value ?? "").replaceAll("`", "\\`") + "`";
}

/** Render a repo-scan report as readable Markdown without trusting project text as Markdown. */
export function renderMarkdownReport(report) {
  if (!report || typeof report !== "object" || !report.profile || !Array.isArray(report.findings) || !Array.isArray(report.evidence)) {
    throw new TypeError("report must be a repo-scan report");
  }
  const profile = report.profile;
  const summary = report.summary ?? {};
  const lines = [
    "# Repository scan: " + inlineCode(profile.root_name ?? "unknown"),
    "",
    "- **Scan ID:** " + inlineCode(report.scan_id ?? "unknown"),
    "- **Captured:** " + markdownText(profile.captured_at ?? "unknown"),
    "- **Files:** " + String(profile.file_count ?? 0),
    "- **Directories:** " + String(profile.directory_count ?? 0),
    "- **Inventory complete:** " + (report.incomplete ? "No" : "Yes"),
    "",
    "## Project profile",
    "",
    "- **Languages:** " + markdownText(Object.entries(profile.languages ?? {}).map(([name, count]) => name + " (" + count + ")").join(", ") || "Not detected"),
    "- **Ecosystems:** " + markdownText((profile.ecosystems ?? []).join(", ") || "Not detected"),
    "- **Frameworks:** " + markdownText((profile.frameworks ?? []).join(", ") || "Not detected"),
    "- **Tests detected:** " + (profile.has_tests ? "Yes" : "No"),
    "- **CI detected:** " + (profile.has_ci ? "Yes" : "No"),
    "- **README demo signal:** " + (profile.has_readme_demo ? "Detected" : "Not detected"),
    "",
    "## Architecture signals",
    "",
    "- **Top-level components:** " + markdownText((profile.top_level_components ?? []).join(", ") || "Not detected"),
    "- **Workspace candidates:** " + markdownText((profile.workspace_candidates ?? []).join(", ") || "Not detected"),
    "- **Launch scripts:** " + markdownText((profile.launch_script_names ?? []).join(", ") || "Not detected"),
    "- **Entry-point candidates:** " + String(profile.entry_point_candidates?.length ?? 0),
    ""
  ];
  for (const candidate of profile.entry_point_candidates ?? []) {
    lines.push("  - " + inlineCode(candidate.path) + " — " + markdownText(candidate.kind) + "; " + (candidate.exists ? "present" : "not present in inventory"));
  }
  lines.push("", "## Findings", "", "- **Total:** " + String(summary.finding_count ?? report.findings.length));
  for (const severity of ["critical", "high", "medium", "low", "info"]) {
    const count = summary.by_severity?.[severity] ?? report.findings.filter((item) => item.severity === severity).length;
    lines.push("- **" + severity[0].toUpperCase() + severity.slice(1) + ":** " + String(count));
  }
  lines.push("");
  if (report.findings.length === 0) {
    lines.push("No findings were produced by the enabled checks.");
  } else {
    const evidenceById = new Map(report.evidence.map((item) => [item.id, item]));
    for (const finding of report.findings) {
      lines.push("### " + markdownText(finding.title));
      lines.push("");
      lines.push("- **Severity:** " + markdownText(finding.severity));
      lines.push("- **Status:** " + markdownText(finding.status));
      lines.push("- **Confidence:** " + Math.round((finding.confidence ?? 0) * 100) + "%");
      if (finding.rule_id) lines.push("- **Rule:** " + inlineCode(finding.rule_id));
      if (finding.affected_paths?.length) lines.push("- **Affected paths:** " + finding.affected_paths.map(inlineCode).join(", "));
      if (finding.description) lines.push("- **Description:** " + markdownText(finding.description));
      for (const recommendation of finding.recommendations ?? []) {
        lines.push("- **Recommendation:** " + markdownText(recommendation));
      }
      for (const id of finding.evidence_ids ?? []) {
        const item = evidenceById.get(id);
        if (item) lines.push("- **Evidence:** " + markdownText(item.claim) + " (" + inlineCode(item.source?.reference ?? id) + ")");
      }
      lines.push("");
    }
  }
  lines.push("## Coverage", "");
  for (const item of report.coverage ?? []) lines.push("- " + markdownText(item));
  lines.push("", "## Limitations", "");
  for (const item of report.limitations ?? []) lines.push("- " + markdownText(item));
  if (report.incomplete) lines.push("- The repository inventory is incomplete. Absence-based findings may have been suppressed.");
  lines.push("", "---", "", "Generated by DEVKIT Project Intelligence. A clean report is not proof of security or correctness.", "");
  return lines.join("\n");
}
